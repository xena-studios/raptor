// The browser's queries are short: what's on screen, not a cache.
export const schemaKey = (nodeId: string, serverId: string, id: string) => [
  "db-schema",
  nodeId,
  serverId,
  id,
];

// dbCommand runs one of the browser's commands and returns its result.
export async function dbCommand<T>(
  nodeId: string,
  serverId: string,
  action: string,
  params: Record<string, unknown>,
): Promise<T> {
  const res = await commandClient.execute({
    nodeId,
    serverId,
    action,
    paramsJson: JSON.stringify(params),
  });
  return (res.resultJson ? JSON.parse(res.resultJson) : {}) as T;
}

export function useSchema(nodeId: string, serverId: string, id: string) {
  return useQuery({
    queryKey: schemaKey(nodeId, serverId, id),
    queryFn: async () =>
      (await dbCommand<{ tables: Table[] }>(nodeId, serverId, "db.schema", { id })).tables,
    retry: false,
  });
}

// tableKey is how a table is told apart: its schema and name.
export function tableKey(t: { schema?: string; name: string }): string {
  return t.schema && t.schema !== "public" ? `${t.schema}.${t.name}` : t.name;
}

// quote is a name as an identifier in the engine's SQL.
export function quote(engine: Engine, name: string): string {
  return engine === "postgres"
    ? `"${name.replaceAll('"', '""')}"`
    : `\`${name.replaceAll("`", "``")}\``;
}

export function tableRef(engine: Engine, t: { schema?: string; name: string }): string {
  return engine === "postgres" && t.schema
    ? `${quote(engine, t.schema)}.${quote(engine, t.name)}`
    : quote(engine, t.name);
}

// literal is a value as a SQL string literal.
export function literal(value: string): string {
  return `'${value.replaceAll("'", "''").replaceAll("\\", "\\\\")}'`;
}

// pgLiteral is a value as a PostgreSQL string literal (backslashes are
// ordinary there).
export function pgLiteral(value: string): string {
  return `'${value.replaceAll("'", "''")}'`;
}

export type NewColumn = {
  name: string;
  type: string;
  nullable: boolean;
  default?: string; // an SQL expression, as typed
  primary?: boolean;
  auto?: boolean; // auto increment / identity
};

function columnSQL(engine: Engine, c: NewColumn): string {
  let s = `${quote(engine, c.name)} ${c.type.trim()}`;
  if (c.auto) s += engine === "postgres" ? " GENERATED BY DEFAULT AS IDENTITY" : " AUTO_INCREMENT";
  if (!c.nullable) s += " NOT NULL";
  if (c.default?.trim()) s += ` DEFAULT ${c.default.trim()}`;
  return s;
}

export function createTableSQL(engine: Engine, name: string, cols: NewColumn[]): string {
  const lines = cols.map((c) => `  ${columnSQL(engine, c)}`);
  const pk = cols.filter((c) => c.primary).map((c) => quote(engine, c.name));
  if (pk.length) lines.push(`  PRIMARY KEY (${pk.join(", ")})`);
  return `CREATE TABLE ${quote(engine, name)} (\n${lines.join(",\n")}\n)`;
}

export function addColumnSQL(engine: Engine, t: Table, c: NewColumn): string {
  return `ALTER TABLE ${tableRef(engine, t)} ADD COLUMN ${columnSQL(engine, c)}`;
}

export function dropColumnSQL(engine: Engine, t: Table, column: string): string {
  return `ALTER TABLE ${tableRef(engine, t)} DROP COLUMN ${quote(engine, column)}`;
}

export function addIndexSQL(
  engine: Engine,
  t: Table,
  name: string,
  columns: string[],
  unique: boolean,
): string {
  return `CREATE ${unique ? "UNIQUE " : ""}INDEX ${quote(engine, name)} ON ${tableRef(engine, t)} (${columns
    .map((c) => quote(engine, c))
    .join(", ")})`;
}

export function dropIndexSQL(engine: Engine, t: Table, index: string): string {
  return engine === "postgres"
    ? `DROP INDEX ${t.schema ? `${quote(engine, t.schema)}.` : ""}${quote(engine, index)}`
    : `DROP INDEX ${quote(engine, index)} ON ${tableRef(engine, t)}`;
}

export function renameTableSQL(engine: Engine, t: Table, to: string): string {
  return engine === "postgres"
    ? `ALTER TABLE ${tableRef(engine, t)} RENAME TO ${quote(engine, to)}`
    : `RENAME TABLE ${tableRef(engine, t)} TO ${quote(engine, to)}`;
}

export function dropTableSQL(engine: Engine, t: Table): string {
  return `DROP ${t.kind === "view" ? "VIEW" : "TABLE"} ${tableRef(engine, t)}`;
}

